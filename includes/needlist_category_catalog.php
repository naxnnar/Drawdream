/**
 * จับคู่ชื่อสิ่งของกับหมวดหมู่เมื่อโหลดข้อมูลแก้ไขจาก DB
 */
function drawdream_needlist_resolve_item_category(string $itemName, string $rowCat = ''): string
{
    global $categoryItems, $itemCategories;

    foreach ($categoryItems as $catName => $optList) {
        if (in_array($itemName, $optList, true)) {
            return $catName;
        }
    }
    if ($rowCat !== '' && in_array($rowCat, $itemCategories, true)) {
        return $rowCat;
    }

    return 'อื่นๆ ที่จำเป็นเฉพาะทาง';
}
